// Turns design/command-center-DESIGN.md into the token files of the web and the app.
// The design document is the only source: edit it, then run `node scripts/design-tokens.mjs`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = "design/command-center-DESIGN.md";
const header = `Generated by scripts/design-tokens.mjs from ${source}. Do not edit.`;

// Reads the front matter. It only needs maps of scalars nested by indentation, which is all the document uses.
export function readDesign(path) {
  const front = readFileSync(path, "utf8").split(/^---\s*$/m)[1];
  const design = {};
  const stack = [{ indent: -1, map: design }];
  for (const line of front.split("\n")) {
    if (!line.trim()) continue;
    const match = /^(\s*)"?([A-Za-z0-9_-]+)"?:\s*(.*)$/.exec(line);
    if (!match) throw new Error(`cannot read design line: ${line}`);
    const indent = match[1].length;
    const raw = match[3].trim();
    while (stack.at(-1).indent >= indent) stack.pop();
    const parent = stack.at(-1).map;
    if (raw === "") {
      parent[match[2]] = {};
      stack.push({ indent, map: parent[match[2]] });
    } else {
      parent[match[2]] = scalar(raw);
    }
  }
  return design;
}

function scalar(raw) {
  if (raw.startsWith('"') && raw.endsWith('"')) return raw.slice(1, -1);
  const number = Number(raw);
  return Number.isNaN(number) ? raw : number;
}

// Replaces references such as {colors.primary} with the value they point to.
function resolve(value, design) {
  if (typeof value === "string") {
    return value.replace(/\{([a-z0-9.-]+)\}/gi, (_, path) => {
      const target = path.split(".").reduce((node, key) => node?.[key], design);
      if (target === undefined) throw new Error(`unknown design reference: ${path}`);
      return typeof target === "object" ? JSON.stringify(target) : String(target);
    });
  }
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, resolve(child, design)]));
  }
  return value;
}

const camel = (name) => {
  const leading = /^(\d+)(.*)$/.exec(name); // "2xl" is not a Kotlin name: it becomes "xl2"
  const safe = leading ? `${leading[2]}${leading[1]}` : name;
  return safe.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
};
const pascal = (name) => camel(name).replace(/^./, (c) => c.toUpperCase());
const px = (value) => Number(String(value).replace("px", ""));
const rem = (value) => Number(String(value).replace("rem", "")) * 16;
const float = (value) => `${Number(value)}f`;

// The document names four dark colors. In dark mode they replace these workspace roles, on the web and in the app.
// Borders take the shell's faint white line, because the document gives no dark outline.
const darkRoles = {
  background: "dark-background",
  "on-background": "dark-on-surface",
  surface: "dark-surface",
  "surface-soft": "dark-surface",
  "surface-elevated": "dark-surface",
  "on-surface": "dark-on-surface",
  "on-surface-muted": "dark-on-surface-muted",
  outline: "shell-border",
  "outline-strong": "shell-border",
};

// A color as a Kotlin ARGB literal. Accepts #rrggbb (with an optional opacity), rgba(...) and transparent.
function argb(value, opacity = 1) {
  const byte = (n) => Math.round(Number(Number(n).toFixed(6))).toString(16).padStart(2, "0").toUpperCase();
  if (value === "transparent") return "0x00000000L";
  const rgba = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(value);
  if (rgba) return `0x${byte(rgba[4] * 255)}${byte(rgba[1])}${byte(rgba[2])}${byte(rgba[3])}L`;
  if (/^#[0-9a-f]{6}$/i.test(value)) return `0x${byte(opacity * 255)}${value.slice(1).toUpperCase()}L`;
  throw new Error(`cannot read color: ${value}`);
}

function typeScript(design) {
  const tokens = { ...design, components: resolve(design.components, design) };
  return `// ${header}\nexport const designTokens = ${JSON.stringify(tokens, null, 2)} as const;\n`;
}

// The web's Tailwind build uses the prefix "sf", so its utilities never share a name with the Axzy UI System's.
// Tailwind emits each theme value as --sf-<name>, which is what the hand-written CSS reads.
function css(design) {
  const theme = [
    // Tailwind's own palette, radii, shadows, fonts and text sizes are cleared: only the design's exist.
    ...["color", "radius", "shadow", "font", "text"].map((namespace) => `  --${namespace}-*: initial;`),
    ...Object.entries(design.colors).map(([key, value]) => `  --color-${key}: ${value};`),
    ...Object.entries(design.rounded).filter(([key]) => key !== "pill").map(([key, value]) => `  --radius-${key}: ${value};`),
    ...Object.entries(design.shadows).map(([key, value]) => `  --shadow-${key}: ${value};`),
    `  --font-sans: ${design.typography["body-md"].fontFamily};`,
    `  --font-mono: ${design.typography["code-sm"].fontFamily};`,
    // One text utility per type style (sf:text-headline-lg, sf:text-label-sm, ...), carrying size, line height, weight and tracking.
    ...Object.entries(design.typography).flatMap(([key, style]) => [
      `  --text-${key}: ${style.fontSize};`,
      `  --text-${key}--line-height: ${style.lineHeight};`,
      `  --text-${key}--font-weight: ${style.fontWeight};`,
      ...(style.letterSpacing ? [`  --text-${key}--letter-spacing: ${style.letterSpacing};`] : []),
    ]),
  ];

  const vars = [];
  const add = (prefix, map) => Object.entries(map).forEach(([key, value]) => vars.push(`  --sf-${prefix}-${key}: ${value};`));
  add("layout", design.layout);
  add("motion", design.motion);
  add("elevation", design.elevation);
  // The shell's faint border: its color at its opacity, written as rgba so the browser reports it the same way.
  const rgba = (hex, alpha) => {
    const n = parseInt(hex.slice(1), 16);
    return `rgba(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}, ${alpha})`;
  };
  vars.push(`  --sf-shell-border: ${rgba(design.colors["shell-border"], design.elevation["shell-border-opacity"])};`);
  // Component specs, such as the shell's background or a button's height. Typography references are objects and stay out.
  const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
  for (const [name, props] of Object.entries(resolve(design.components, design))) {
    for (const [prop, value] of Object.entries(props)) {
      if (typeof value === "string" && !value.startsWith("{")) vars.push(`  --sf-c-${name}-${kebab(prop)}: ${value};`);
    }
  }
  // Dark mode. The Axzy UI System sets the class on <html>, following the system setting.
  const dark = Object.entries(darkRoles).map(([role, target]) =>
    `  --sf-color-${role}: var(${target === "shell-border" ? "--sf-shell-border" : `--sf-color-${target}`});`);
  // A part of the page that keeps the light look in dark mode, such as the entry screen (design-system.md section 7).
  const light = Object.keys(darkRoles).map((role) => `  --sf-color-${role}: ${design.colors[role]};`);
  return `/* ${header} */\n@theme static {\n${theme.join("\n")}\n}\n\n:root {\n${vars.join("\n")}\n}\n\n.dark {\n${dark.join("\n")}\n}\n\n.dark [data-light] {\n${light.join("\n")}\n}\n`;
}

function kotlin(design) {
  const block = (name, lines) => `\tobject ${name} {\n${lines.map((line) => (line ? `\t\t${line}` : "")).join("\n")}\n\t}`;
  const colors = Object.entries(design.colors);
  const colorLines = [
    ...colors.map(([key, hex]) => `const val ${camel(key)} = ${argb(hex)}`),
    "",
    "// The design's own names, for lookups and for the tests that compare against the document.",
    "val byName: Map<String, Long> = mapOf(",
    ...colors.map(([key]) => `\t"${key}" to ${camel(key)},`),
    ")",
  ];
  const darkLines = Object.entries(darkRoles).map(([role, target]) =>
    `const val ${camel(role)} = ${target === "shell-border"
      ? argb(design.colors["shell-border"], design.elevation["shell-border-opacity"])
      : argb(design.colors[target])}`);
  const numbers = (map, convert) => Object.entries(map).map(([key, value]) => `const val ${camel(key)} = ${convert(value)}`);
  const typography = Object.entries(design.typography).map(([key, style]) => {
    const size = rem(style.fontSize);
    const lineHeight = typeof style.lineHeight === "number" ? size * style.lineHeight : rem(style.lineHeight);
    const spacing = style.letterSpacing ? Number(style.letterSpacing.replace("em", "")) : 0;
    return `val ${camel(key)} = TypeStyle(fontSize = ${float(size)}, fontWeight = ${style.fontWeight}, lineHeight = ${float(lineHeight)}, `
      + `letterSpacingEm = ${float(spacing)}, monospace = ${style.fontFamily.startsWith("ui-monospace")})`;
  });
  const motion = Object.entries(design.motion).map(([key, value]) =>
    String(value).endsWith("ms") ? `const val ${camel(key)} = ${Number(String(value).replace("ms", ""))}` : `const val ${camel(key)} = "${value}"`);
  const elevation = Object.entries(design.elevation).map(([key, value]) =>
    String(value).endsWith("px") ? `const val ${camel(key)} = ${px(value)}` : `const val ${camel(key)} = ${float(value)}`);
  // Each component with its references replaced by values. "6px 12px" becomes vertical and horizontal padding.
  const components = Object.entries(design.components).map(([name, props]) => {
    const args = Object.entries(props).flatMap(([prop, raw]) => {
      if (prop === "typography") return [`typography = Typography.${camel(raw.slice("{typography.".length, -1))}`];
      const value = resolve(raw, design);
      if (prop === "backgroundColor" || prop === "textColor") return [`${prop} = ${argb(value)}`];
      if (prop === "padding") {
        const [vertical, horizontal = vertical] = value.split(/\s+/).map(px);
        return [`paddingVertical = ${vertical}`, `paddingHorizontal = ${horizontal}`];
      }
      return [`${prop} = ${px(value)}`];
    });
    return `val ${camel(name)} = Component(${args.join(", ")})`;
  });

  return [
    `// ${header}`,
    "package com.axzydev.stock.ui.theme",
    "",
    "// Colors are ARGB. Sizes are in dp, text sizes in sp, durations in milliseconds.",
    "object DesignTokens {",
    "\tclass TypeStyle(val fontSize: Float, val fontWeight: Int, val lineHeight: Float, val letterSpacingEm: Float, val monospace: Boolean)",
    "",
    "\t// A component as the design specifies it. A size the design leaves out is 0.",
    "\tclass Component(",
    "\t\tval backgroundColor: Long = 0x00000000L,",
    "\t\tval textColor: Long = 0x00000000L,",
    "\t\tval typography: TypeStyle? = null,",
    "\t\tval rounded: Int = 0,",
    "\t\tval height: Int = 0,",
    "\t\tval width: Int = 0,",
    "\t\tval paddingVertical: Int = 0,",
    "\t\tval paddingHorizontal: Int = 0,",
    "\t)",
    "",
    block("Colors", colorLines),
    "",
    "\t// Dark mode: the workspace roles that change, each with the color that replaces it.",
    block("DarkColors", darkLines),
    "",
    block("Rounded", numbers(design.rounded, px)),
    "",
    block("Spacing", numbers(design.spacing, px)),
    "",
    block("Layout", numbers(design.layout, px)),
    "",
    block("Motion", motion),
    "",
    block("Elevation", elevation),
    "",
    block("Typography", typography),
    "",
    block("Components", components),
    "}",
    "",
  ].join("\n");
}

// The color of the Android window before the first frame, so the app does not open on a white or black flash.
function androidColors(hex) {
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${header} -->\n<resources>\n    <color name="design_background">${hex.toUpperCase()}</color>\n</resources>\n`;
}

export function outputs(design) {
  return {
    "web/src/shared/ui/design-tokens.ts": typeScript(design),
    "web/src/app/design-tokens.css": css(design),
    "app/shared/src/commonMain/kotlin/com/axzydev/stock/ui/theme/DesignTokens.kt": kotlin(design),
    "app/androidApp/src/main/res/values/design_colors.xml": androidColors(design.colors.background),
    "app/androidApp/src/main/res/values-night/design_colors.xml": androidColors(design.colors["dark-background"]),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, content] of Object.entries(outputs(readDesign(join(root, source))))) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
    console.log(`wrote ${path}`);
  }
}
