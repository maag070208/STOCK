// Turns the brand glyph (design/brand/master) into vector drawables for the app, light and dark.
// Only the format changes: every path, color and stroke is the master's. The frame is cropped to the art,
// which sits in the middle of the master's 1024 x 1024 square.
// Run `node scripts/brand-vectors.mjs` after the brand pack changes.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const header = "Generated by scripts/brand-vectors.mjs from design/brand/master. Do not edit.";

// The art's bounds in the master's own coordinates: the belt's outer edge and the top of the boxes.
const FRAME = { x: 104, y: 42, width: 392, height: 156 };

const attributes = (tag) => Object.fromEntries([...tag.matchAll(/([a-z-]+)="([^"]*)"/g)].map((match) => [match[1], match[2]]));

// The shapes of the glyph, in order: filled paths, the belt (a rounded rectangle), and the stroked chevrons.
export function readGlyph(svg) {
  const shapes = [];
  let group = {};
  for (const match of svg.matchAll(/<(\/?)(g|path|rect)\b([^>]*?)(\/?)>/g)) {
    const [, closing, tag, rest, selfClosing] = match;
    const attrs = attributes(rest);
    if (tag === "g") {
      group = closing ? {} : selfClosing ? group : attrs;
      continue;
    }
    const style = { ...group, ...attrs };
    if (tag === "rect") {
      const x = Number(style.x), y = Number(style.y), w = Number(style.width), h = Number(style.height), r = Number(style.rx);
      style.d = `M${x + r},${y} H${x + w - r} A${r},${r} 0 0 1 ${x + w - r},${y + h} H${x + r} A${r},${r} 0 0 1 ${x + r},${y} Z`;
    }
    shapes.push(style);
  }
  return shapes;
}

function vector(shapes) {
  const lines = shapes.map((shape) => {
    const props = [`android:pathData="${shape.d}"`];
    if (shape.fill && shape.fill !== "none") props.push(`android:fillColor="${shape.fill}"`);
    if (shape["fill-rule"] === "evenodd") props.push(`android:fillType="evenOdd"`);
    if (shape.stroke) {
      props.push(`android:strokeColor="${shape.stroke}"`, `android:strokeWidth="${shape["stroke-width"]}"`);
      if (shape["stroke-linecap"]) props.push(`android:strokeLineCap="${shape["stroke-linecap"]}"`);
      if (shape["stroke-linejoin"]) props.push(`android:strokeLineJoin="${shape["stroke-linejoin"]}"`);
    }
    return `        <path ${props.join(" ")} />`;
  });
  return [
    `<?xml version="1.0" encoding="utf-8"?>`,
    `<!-- ${header} -->`,
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"`,
    `    android:width="${FRAME.width / 2}dp" android:height="${FRAME.height / 2}dp"`,
    `    android:viewportWidth="${FRAME.width}" android:viewportHeight="${FRAME.height}">`,
    `    <group android:translateX="${-FRAME.x}" android:translateY="${-FRAME.y}">`,
    ...lines,
    `    </group>`,
    `</vector>`,
    ``,
  ].join("\n");
}

export function outputs() {
  const out = {};
  for (const variant of ["light", "dark"]) {
    const svg = readFileSync(join(root, `design/brand/master/stockflow-glyph-${variant}.svg`), "utf8");
    out[`app/shared/src/commonMain/composeResources/drawable/stockflow_glyph_${variant}.xml`] = vector(readGlyph(svg));
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, content] of Object.entries(outputs())) {
    writeFileSync(join(root, path), content);
    console.log(`wrote ${path}`);
  }
}
