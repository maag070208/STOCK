// Turns the table in docs/i18n/messages.md into the API's message files, one per language.
// The document is the only source: edit it, then run `node scripts/error-messages.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = "docs/i18n/messages.md";

// One entry per row: | `CODE` | Spanish | English |
export function readMessages(path) {
  const rows = [];
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const match = /^\| `([A-Z_]+)` \| (.+) \| (.+) \|$/.exec(line);
    if (match) rows.push({ code: match[1], es: match[2].trim(), en: match[3].trim() });
  }
  return rows;
}

// The API formats messages with MessageFormat: {{name}} becomes {0}, {1}, ... and an apostrophe is doubled.
function property(code, text) {
  let index = 0;
  const value = text.replace(/'/g, "''").replace(/\{\{[a-zA-Z]+\}\}/g, () => `{${index++}}`);
  return `error.${code.toLowerCase()}=${value}`;
}

export function outputs(rows) {
  const header = `# Generated by scripts/error-messages.mjs from ${source}. Do not edit.\n`;
  const file = (locale) => header + rows.map((row) => property(row.code, row[locale])).join("\n") + "\n";
  return {
    "api/src/main/resources/messages/errors_es.properties": file("es"),
    "api/src/main/resources/messages/errors_en.properties": file("en"),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, content] of Object.entries(outputs(readMessages(join(root, source))))) {
    writeFileSync(join(root, path), content);
    console.log(`wrote ${path}`);
  }
}
