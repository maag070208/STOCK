// Turns the table in docs/i18n/documents.md into the API's document labels, one file per language.
// The document is the only source: edit it, then run `node scripts/document-messages.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = "docs/i18n/documents.md";

// One entry per row: | `document.key` | Spanish | English |
export function readLabels(path) {
  const rows = [];
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const match = /^\| `([a-z_.]+)` \| (.+) \| (.+) \|$/.exec(line);
    if (match) rows.push({ key: match[1], es: match[2].trim(), en: match[3].trim() });
  }
  return rows;
}

// A label as a properties line. An apostrophe is doubled, as the error messages do.
function property(row, locale) {
  return `${row.key}=${row[locale].replace(/'/g, "''")}`;
}

export function outputs(rows) {
  const header = `# Generated by scripts/document-messages.mjs from ${source}. Do not edit.\n`;
  const file = (locale) => header + rows.map((row) => property(row, locale)).join("\n") + "\n";
  return {
    "api/src/main/resources/messages/documents_es.properties": file("es"),
    "api/src/main/resources/messages/documents_en.properties": file("en"),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, content] of Object.entries(outputs(readLabels(join(root, source))))) {
    writeFileSync(join(root, path), content);
    console.log(`wrote ${path}`);
  }
}
